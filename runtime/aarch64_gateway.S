.global osrec_aarch64_gateway_enter
.type osrec_aarch64_gateway_enter,%function
osrec_aarch64_gateway_enter:
    sub sp,sp,#32
    stp x0,x1,[sp,#0]
    stp x2,x3,[sp,#16]
    add x1,x0,#G_CONTAINER
    ldp x2,x3,[sp,#16]
    stp x2,x3,[x1,#16]
    ldp x2,x3,[sp,#0]
    stp x2,x3,[x1,#0]
    stp x4,x5,[x1,#32]
    stp x6,x7,[x1,#48]
    stp x8,x9,[x1,#64]
    stp x10,x11,[x1,#80]
    stp x12,x13,[x1,#96]
    stp x14,x15,[x1,#112]
    stp x16,x17,[x1,#128]
    stp x18,x19,[x1,#144]
    stp x20,x21,[x1,#160]
    stp x22,x23,[x1,#176]
    stp x24,x25,[x1,#192]
    stp x26,x27,[x1,#208]
    stp x28,x29,[x1,#224]
    str x30,[x1,#240]
    add x2,sp,#32
    str x2,[x1,#F_SP]
    adr x2,osrec_gateway_return
    str x2,[x1,#F_PC]
    mrs x2,nzcv
    mrs x3,daif
    orr x2,x2,x3
    mov x3,#5
    orr x2,x2,x3
    str x2,[x1,#F_PSTATE]
    mrs x2,cpacr_el1
    str x2,[x0,#G_CPACR]
    orr x3,x2,#0x300000
    msr cpacr_el1,x3
    isb
    save_fp x1
    mrs x2,vbar_el1
    str x2,[x0,#G_VBAR]
    mrs x2,tpidr_el1
    str x2,[x0,#G_TPIDR_EL1]
    mrs x2,sp_el0
    str x2,[x0,#G_SP_EL0]
    mrs x2,elr_el1
    str x2,[x0,#G_ELR]
    mrs x2,spsr_el1
    str x2,[x0,#G_SPSR]
    ldr x2,[x0,#G_KERNEL_SP]
    mov sp,x2
    msr tpidr_el1,x0
    adr x2,osrec_gateway_vectors
    msr vbar_el1,x2
    isb
    ldr x0,[x0,#G_APP]
    ldr x2,[x0,#F_SP]
    msr sp_el0,x2
    restore_frame x0
    eret
osrec_gateway_return:
    ldr x1,[x0,#G_CPACR]
    msr cpacr_el1,x1
    isb
    ldr x1,[x0,#G_ELR]
    msr elr_el1,x1
    ldr x1,[x0,#G_SPSR]
    msr spsr_el1,x1
    ldr w0,[x0,#G_STATUS]
    ret
.balign 2048
osrec_gateway_vectors:
.rept 16
    b osrec_gateway_exception
    .space 124
.endr
osrec_gateway_exception:
    sub sp,sp,#F_STACK_BYTES
    stp x0,x1,[sp,#0]
    stp x2,x3,[sp,#16]
    stp x4,x5,[sp,#32]
    stp x6,x7,[sp,#48]
    stp x8,x9,[sp,#64]
    stp x10,x11,[sp,#80]
    stp x12,x13,[sp,#96]
    stp x14,x15,[sp,#112]
    stp x16,x17,[sp,#128]
    stp x18,x19,[sp,#144]
    stp x20,x21,[sp,#160]
    stp x22,x23,[sp,#176]
    stp x24,x25,[sp,#192]
    stp x26,x27,[sp,#208]
    stp x28,x29,[sp,#224]
    str x30,[sp,#240]
    mrs x2,sp_el0
    str x2,[sp,#F_SP]
    mrs x2,elr_el1
    str x2,[sp,#F_PC]
    mrs x2,spsr_el1
    str x2,[sp,#F_PSTATE]
    save_fp sp
    mrs x0,tpidr_el1
    mov x1,sp
    mrs x2,esr_el1
    bl osrec_aarch64_gateway_trap
    cbnz w0,osrec_gateway_container
    mrs x0,tpidr_el1
    ldr x0,[x0,#G_APP]
    add sp,sp,#F_STACK_BYTES
    ldr x2,[x0,#F_SP]
    msr sp_el0,x2
    restore_frame x0
    eret
osrec_gateway_container:
    mrs x0,tpidr_el1
    add sp,sp,#F_STACK_BYTES
    ldr x2,[x0,#G_VBAR]
    msr vbar_el1,x2
    ldr x2,[x0,#G_TPIDR_EL1]
    msr tpidr_el1,x2
    ldr x2,[x0,#G_SP_EL0]
    msr sp_el0,x2
    isb
    add x0,x0,#G_CONTAINER
    ldr x2,[x0,#F_SP]
    mov sp,x2
    restore_frame x0
    eret
