/* Every instruction runs at EL0. Guest SP is virtual; actual SP is private.
 * Only unprivileged NZCV/FPCR/FPSR system-register accesses occur here. */
    .arch armv8-a
    .text
    .balign 4
    .global flat_enter
    .type flat_enter,%function
flat_enter:
    sub sp,sp,#192
    stp x19,x20,[sp,#0]
    stp x21,x22,[sp,#16]
    stp x23,x24,[sp,#32]
    stp x25,x26,[sp,#48]
    stp x27,x28,[sp,#64]
    stp x29,x30,[sp,#80]
    stp d8,d9,[sp,#96]
    stp d10,d11,[sp,#112]
    stp d12,d13,[sp,#128]
    stp d14,d15,[sp,#144]
    mrs x3,fpcr
    mrs x4,fpsr
    stp x3,x4,[sp,#160]
    mov x3,sp
    str x3,[x0,#16]
    ldr x3,[x0,#8]
    mov sp,x3
    sub sp,sp,#800
    mov x3,sp
    mov x4,#50
1:  ldp x5,x6,[x1],#16
    stp x5,x6,[x3],#16
    subs x4,x4,#1
    b.ne 1b
    mov x0,x2
    b flat_restore
    .size flat_enter,.-flat_enter

    .global flat_capture_rest
    .type flat_capture_rest,%function
flat_capture_rest:
    stp x2,x3,[sp,#16]
    stp x4,x5,[sp,#32]
    stp x6,x7,[sp,#48]
    stp x8,x9,[sp,#64]
    stp x10,x11,[sp,#80]
    stp x12,x13,[sp,#96]
    stp x14,x15,[sp,#112]
    stp x16,x17,[sp,#128]
    stp x18,x19,[sp,#144]
    stp x20,x21,[sp,#160]
    stp x22,x23,[sp,#176]
    stp x24,x25,[sp,#192]
    stp x26,x27,[sp,#208]
    stp x28,x29,[sp,#224]
    str x30,[sp,#240]
    mrs x2,nzcv
    str x2,[sp,#264]
    stp q0,q1,[sp,#272]
    stp q2,q3,[sp,#304]
    stp q4,q5,[sp,#336]
    stp q6,q7,[sp,#368]
    stp q8,q9,[sp,#400]
    stp q10,q11,[sp,#432]
    stp q12,q13,[sp,#464]
    stp q14,q15,[sp,#496]
    stp q16,q17,[sp,#528]
    stp q18,q19,[sp,#560]
    stp q20,q21,[sp,#592]
    stp q22,q23,[sp,#624]
    stp q24,q25,[sp,#656]
    stp q26,q27,[sp,#688]
    stp q28,q29,[sp,#720]
    stp q30,q31,[sp,#752]
    mrs x2,fpsr
    mrs x3,fpcr
    str w2,[sp,#784]
    str w3,[sp,#788]
    mov x1,x0
    adrp x0,flat_active
    ldr x0,[x0,:lo12:flat_active]
    ldr x0,[x0,#0]
    str x0,[sp,#248]
    mov x0,sp
    bl flat_dispatch
    cbz x0,flat_escape
    b flat_restore
    .size flat_capture_rest,.-flat_capture_rest

    .type flat_restore,%function
flat_restore:
    mov x16,x0
    ldp q0,q1,[sp,#272]
    ldp q2,q3,[sp,#304]
    ldp q4,q5,[sp,#336]
    ldp q6,q7,[sp,#368]
    ldp q8,q9,[sp,#400]
    ldp q10,q11,[sp,#432]
    ldp q12,q13,[sp,#464]
    ldp q14,q15,[sp,#496]
    ldp q16,q17,[sp,#528]
    ldp q18,q19,[sp,#560]
    ldp q20,q21,[sp,#592]
    ldp q22,q23,[sp,#624]
    ldp q24,q25,[sp,#656]
    ldp q26,q27,[sp,#688]
    ldp q28,q29,[sp,#720]
    ldp q30,q31,[sp,#752]
    ldr w0,[sp,#784]
    ldr w1,[sp,#788]
    msr fpsr,x0
    msr fpcr,x1
    ldr x0,[sp,#264]
    msr nzcv,x0
    ldp x0,x1,[sp,#0]
    ldp x2,x3,[sp,#16]
    ldp x4,x5,[sp,#32]
    ldp x6,x7,[sp,#48]
    ldp x8,x9,[sp,#64]
    ldp x10,x11,[sp,#80]
    ldp x12,x13,[sp,#96]
    ldp x14,x15,[sp,#112]
    ldp x18,x19,[sp,#144]
    ldp x20,x21,[sp,#160]
    ldp x22,x23,[sp,#176]
    ldp x24,x25,[sp,#192]
    ldp x26,x27,[sp,#208]
    ldp x28,x29,[sp,#224]
    ldr x30,[sp,#240]
    br x16
    .size flat_restore,.-flat_restore

    .global flat_escape
    .type flat_escape,%function
flat_escape:
    adrp x0,flat_active
    ldr x0,[x0,:lo12:flat_active]
    ldr x0,[x0,#16]
    mov sp,x0
    ldp x3,x4,[sp,#160]
    msr fpcr,x3
    msr fpsr,x4
    ldp d8,d9,[sp,#96]
    ldp d10,d11,[sp,#112]
    ldp d12,d13,[sp,#128]
    ldp d14,d15,[sp,#144]
    ldp x19,x20,[sp,#0]
    ldp x21,x22,[sp,#16]
    ldp x23,x24,[sp,#32]
    ldp x25,x26,[sp,#48]
    ldp x27,x28,[sp,#64]
    ldp x29,x30,[sp,#80]
    add sp,sp,#192
    ret
    .size flat_escape,.-flat_escape
    .section .note.GNU-stack,"",%progbits
