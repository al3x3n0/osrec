#!/usr/bin/env python3
"""Package an existing validated, lowered trap image for native arm64 Linux.

No kernel is recompiled or replaced with host syscalls. The physical store is a
sparse copy of the transformed live RAM; native mappings share its page aliases.
The package is independent of the original dump, vmlinux and mini-OS monitor.
"""
import argparse
import hashlib
import json
import mmap
import struct
from pathlib import Path

PAGE = 4096
MASK = (1 << 48) - 1
MAGIC = 0x3145564954414e4c


def package(image, out, user_elf=None):
    from kernel_source_verify import Elf
    from source_image_el0 import instruction_ranges, BRK_SITE, MONITOR_PA, MONITOR_SIZE
    image, out = Path(image).resolve(), Path(out).resolve()
    m = json.loads((image / 'manifest.json').read_text())
    if m.get('execution') != 'el0-minios' or not m.get('lowered') or m.get('dispatch', 'traps') != 'traps':
        raise ValueError('native packaging requires a lowered EL0 image with trap dispatch')
    raw = (image / 'image.elf').read_bytes()
    if hashlib.sha256(raw).hexdigest() != m['image_sha256']:
        raise ValueError('image hash does not match manifest')
    phoff, = struct.unpack_from('<Q', raw, 32)
    stride, count = struct.unpack_from('<HH', raw, 54)
    segments = []
    for i in range(count):
        kind, _, offset, _, pa, size, memsize, _ = struct.unpack_from('<IIQQQQQQ', raw, phoff + i * stride)
        if kind == 1:
            if size != memsize or offset + size > len(raw):
                raise ValueError('unsupported/truncated physical segment')
            segments.append((pa, raw[offset:offset+size]))
    def read(pa, size):
        result = bytearray(size)
        for start, data in segments:
            lo, hi = max(start, pa), min(start+len(data), pa+size)
            if lo < hi:
                result[lo-pa:hi-pa] = data[lo-start:hi-start]
        return bytes(result)
    monitor = Elf(image / 'monitor.elf')
    symbols = {s['name']: s['value'] for s in monitor.symbols}
    def symbol(name, size):
        return read(symbols[name] - int(m['monitor_va'], 16) + MONITOR_PA, size)
    def q(name):
        return struct.unpack('<Q', symbol(name, 8))[0]
    ranges = symbol('osrec_kernel_ranges', q('osrec_kernel_range_count')*16)
    origins = symbol('osrec_veneer_origins', q('osrec_veneer_count')*8)
    veneer = q('osrec_veneer_base')
    veneer_count = q('osrec_veneer_count')
    veneer_end = veneer + veneer_count*16
    # Read the original permission view generated by the validated image. The
    # monitor's executable mappings must never be installed in a host process.
    wanted = {int(p['va'], 16) for p in m['pages'] if p['kind'] != 'device'}
    wanted.update(range(veneer, veneer_end, PAGE))
    mappings = []
    def walk(table, level=0, prefix=0, parent=0):
        for i, (d,) in enumerate(struct.iter_unpack('<Q', read(table, PAGE))):
            if not d & 1:
                continue
            va, shift = prefix | i << (12+9*(3-level)), 12+9*(3-level)
            if level < 3 and d & 2:
                walk(d & MASK & ~4095, level+1, va, parent | d)
                continue
            if level == 3 and not d & 2:
                continue
            if parent & (1 << 59): d |= 1 << 53
            if parent & (1 << 60): d |= 1 << 54
            if parent & (1 << 61): d &= ~(1 << 6)
            if parent & (1 << 62): d |= 1 << 7
            pa = (d & MASK) & ~((1 << shift)-1)
            for k in range(0, 1 << shift, PAGE):
                if va+k in wanted:
                    attrs=d & ~((MASK & ~4095))
                    if veneer <= va+k < veneer_end:
                        attrs &= ~((1<<53)|(1<<54))
                        attrs |= 1<<7
                    mappings.append([va+k, pa+k, PAGE, attrs])
    walk(int(m['ttbr1_user'], 16))
    mappings.sort()
    if {v for v, _, _, _ in mappings} != wanted:
        raise ValueError('kernel mappings missing from image permission tables')
    base = m['ram']['base']
    end = max(m['ram']['base']+m['ram']['size'], max(pa+size for _, pa, size, _ in mappings))
    if any(MONITOR_PA <= pa < MONITOR_PA+MONITOR_SIZE for _, pa, _, _ in mappings):
        raise ValueError('package unexpectedly maps mini-OS monitor memory')
    out.mkdir(parents=True, exist_ok=False)
    with (out / 'memory.bin').open('w+b') as store:
        store.truncate(end-base)
        # Staged DTB-range pages contain captured RAM, not the QEMU boot DTB.
        staged = q('staged_count')
        staged_pages = dict(struct.iter_unpack('<QQ', symbol('staged_pages', staged*16)))
        for pa, data in segments:
            lo, hi = max(base,pa), min(end,pa+len(data))
            if lo < hi:
                store.seek(lo-base);store.write(data[lo-pa:hi-pa])
        for src,dst in staged_pages.items():
            if base <= dst < base+m['ram']['size']:
                store.seek(dst-base);store.write(read(src,PAGE))
    # TLS remains the host thread's TLS. Capture all guest TLS operations in
    # rewritten kernel text, including ones that were legal in the mini-OS.
    sites = {va: (word, kind) for va, word, kind in struct.iter_unpack('<QII', (image/'sites.bin').read_bytes())}
    from source_image import text_ranges
    elf, sections = text_ranges(m['vmlinux'])
    text_pages = {int(p['original_va'],16): int(p['pa'],16) for p in m['pages'] if p['kind']=='text'}
    tls_sites = svc_sites = zero_sites = clock_sites = 0
    with (out/'memory.bin').open('r+b') as store:
        with mmap.mmap(store.fileno(),0) as memory:
            for lo, hi in instruction_ranges(elf, sections):
                for pc in range(lo, hi, 4):
                    pa = text_pages.get(pc & ~4095)
                    if pa is None: continue
                    address = pa+(pc & 4095)-base
                    word, = struct.unpack_from('<I',memory,address)
                    tls = word & 0xfff00000 in (0xd5300000,0xd5100000) and (word>>5 & 65535)==0xde82
                    svc = word & 0xffe0001f == 0xd4000001
                    zero = word & ~31 == 0xd50b7420
                    clock = word & 0xfff00000 == 0xd5300000 and (word>>5 & 65535) in (0xdf01,0xdf02)
                    if tls or svc or zero or clock:
                        va=pc & MASK
                        sites[va]=(word,0)
                        struct.pack_into('<I',memory,address,BRK_SITE)
                        tls_sites += tls
                        svc_sites += svc
                        zero_sites += zero
                        clock_sites += clock
    # Adjacent aliases with identical permissions are one host mmap operation.
    runs=[]
    for v, p, size, attrs in mappings:
        if runs and v==runs[-1][0]+runs[-1][2] and p==runs[-1][1]+runs[-1][2] and attrs==runs[-1][3]:
            runs[-1][2]+=size
        else: runs.append([v,p,size,attrs])
    shadow=(image/'shadow.bin').read_bytes()
    tcr=struct.unpack_from('<Q',shadow,13*8+8192+0xc102*8)[0] # TCR_EL1
    fp=(image/'fp.bin').read_bytes()
    fp_native=fp[:512]+struct.pack('<II',*struct.unpack_from('<QQ',fp,512))
    header=struct.pack('<10Q',MAGIC,1,base,end-base,tcr,len(ranges)//16,len(sites),veneer,len(origins)//8,len(runs))
    context=symbol('osrec_start_context',272)
    with (out/'native.bin').open('wb') as f:
        for part in (header,context,fp_native,shadow,ranges,
                     b''.join(struct.pack('<QII',va,*value) for va,value in sorted(sites.items())),origins,
                     b''.join(struct.pack('<4Q',*run) for run in runs)):
            f.write(part)
    report=dict(format='osrec-native-package-v1',source_image_sha256=m['image_sha256'],
                mappings=len(mappings),mapping_runs=len(runs),sites=len(sites),tls_sites=tls_sites,svc_sites=svc_sites,
                zero_sites=zero_sites,clock_sites=clock_sites,
                memory_size=end-base,initial_pc=hex(struct.unpack_from('<Q',context,256)[0]))
    (out/'manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    if user_elf:
        from source_image_application import build
        report['application']=build(image,out,user_elf)
    return report


if __name__ == '__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('image');p.add_argument('--out',required=True)
    p.add_argument('--user-elf',help='matching static application ELF; enables native continuation')
    a=p.parse_args();print(json.dumps(package(a.image,a.out,a.user_elf),indent=2))
